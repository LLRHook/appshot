import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Track exact bundled bytes, so renaming an uploaded sample cannot make it a real capture. */
export async function writeSampleFingerprints(folder, target) {
	const files = (await readdir(folder)).filter((name) => name.endsWith('.png')).sort();
	if (!files.length) throw new Error('Generate the sample images before their fingerprints.');
	const entries = await Promise.all(
		files.map(async (name) => [
			`/sample/${name}`,
			createHash('sha256')
				.update(await readFile(path.join(folder, name)))
				.digest('hex')
		])
	);
	await writeFile(
		target,
		'// Generated by scripts/sample-assets/fingerprints.mjs; do not edit.\n' +
			'export const SAMPLE_FINGERPRINTS = {\n' +
			entries.map(([url, hash]) => `\t'${url}': '${hash}'`).join(',\n') +
			'\n} as const;\n'
	);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
	await writeSampleFingerprints(
		path.join(app, 'static/sample'),
		path.join(app, 'src/lib/model/sample-fingerprints.generated.ts')
	);
}
